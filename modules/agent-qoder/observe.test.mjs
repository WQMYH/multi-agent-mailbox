import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, readFileSync, readdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { desktop, queueOwnerId } from './desktop.mjs';

test('message observation is scoped, paged and read-only, preserving unknowns and exact prompt text', async t => {
  const root = mkdtempSync(join(tmpdir(), 'qoder-observe-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const directory = join(root, 'delivery'); mkdirSync(directory);
  const config = { root, deliveryDir: directory, workspaceId: '11111111-1111-4111-8111-111111111111', token: 'fixture-config-secret' };
  const path = join(directory, 'send-queue.sqlite'), ownerId = queueOwnerId(config);
  const db = new DatabaseSync(path);
  db.exec(`CREATE TABLE queue_meta(id INTEGER PRIMARY KEY,owner_id TEXT,queue_path TEXT);
    CREATE TABLE sends(seq INTEGER PRIMARY KEY,request_id TEXT,session_id TEXT,workspace_id TEXT,cwd TEXT,
      prompt TEXT,state TEXT,native_ack INTEGER,terminal_outcome TEXT,observed_at TEXT,correlation TEXT,created_at TEXT);`);
  db.prepare('INSERT INTO queue_meta VALUES(1,?,?)').run(ownerId, path.replaceAll('\\', '/').toLowerCase());
  const insert = db.prepare('INSERT INTO sends VALUES(?,?,?,?,?,?,?,?,?,?,?,?)');
  const text = '<script>globalThis.executed=true</script><img src=x onerror="globalThis.executed=true">';
  insert.run(1, 'request-a', 'session-a', config.workspaceId, root, text, 'awaiting_observation', 1, 'completed', '2026-10-02T02:00:00.000Z', 'linked', '2026-10-02T01:00:00.000Z');
  insert.run(2, 'request-b', 'session-b', config.workspaceId, root, 'x'.repeat(17000), 'queued', 0, null, null, 'linked', '2026-10-02T01:01:00.000Z');
  insert.run(3, 'request-c', 'session-c', config.workspaceId, root, 'uncertain body', 'needs_attention', 0, null, null, 'other', '2026-10-02T01:02:00.000Z');
  insert.run(4, 'request-hidden', 'session-d', config.workspaceId, join(root, 'foreign'), 'outside operator root', 'queued', 0, null, null, 'linked', '2026-10-02T01:03:00.000Z');
  db.close();
  const snapshot = () => Object.fromEntries(readdirSync(directory).sort().map(name => [name, readFileSync(join(directory, name)).toString('base64')]));
  const before = snapshot(), read = args => desktop('message_observe', args, config, { assertCurrent() {} });
  const page = await read({ view: 'items', limit: 1, correlation: 'linked' });
  assert.equal(page.items[0].content.text, text); assert.equal(page.items[0].state, 'observed');
  assert.equal(page.items[0].evidence.providerAccepted, true); assert.equal(page.items[0].evidence.businessAccepted, 'unknown');
  const second = await read({ view: 'items', correlation: 'linked', cursor: page.nextCursor });
  assert.equal(second.items.length, 1); assert.equal(second.items[0].requestId, 'request-b');
  assert.equal(second.items[0].content.text.length, 512); assert.equal(second.items[0].content.truncated, true);
  const full = await read({ view: 'detail', requestId: 'request-b' });
  assert.equal(full.item.content.text.length, 16000); assert.equal(full.item.content.truncated, true);
  assert.equal(second.items[0].evidence.providerAccepted, 'unknown');
  const detail = await read({ view: 'detail', deliveryId: 'qoder-delivery:request-a' });
  assert.equal(detail.item.content.text, text); assert.equal(detail.item.trace.events.length, 2);
  const stats = await read({ view: 'stats', limit: 1, correlation: 'linked' });
  assert.equal(stats.stats.total, 2); assert.deepEqual(stats.stats.byState, { observed: 1, queued: 1 });
  assert.deepEqual(stats.stats.providerAccepted, { accepted: 1, unknown: 1 });
  assert.equal((await read({ view: 'detail', requestId: 'request-hidden' })).item, null);
  assert.equal((await read({ view: 'detail', requestId: 'request-c' })).item.evidence.terminalOutcome, 'unknown');
  await assert.rejects(read({ view: 'items', correlation: 'other', cursor: page.nextCursor }), /cursor|filters/);
  await assert.rejects(read({ view: 'items', cursor: 'bad-cursor' }), /cursor/);
  await assert.rejects(read({ view: 'detail' }), /requires/);
  const encoded = JSON.stringify([page, second, detail, stats]);
  for (const secret of [config.token, root, 'queue_path', 'registration_key']) assert.ok(!encoded.includes(secret));
  assert.deepEqual(snapshot(), before);
  const missing = { ...config, deliveryDir: join(root, 'not-created') };
  assert.equal((await desktop('message_observe', { view: 'stats' }, missing)).stats.total, 0);
  assert.deepEqual(readdirSync(root).sort(), ['delivery']);
});
